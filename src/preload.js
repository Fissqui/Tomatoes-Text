// Pont sécurisé entre l'interface et le processus principal.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('frameText', {
  loadLibrary: (project) => ipcRenderer.invoke('library:load', project),
  saveLibraryIndex: (index) => ipcRenderer.invoke('library:saveIndex', index),
  openLibraryFolder: () => ipcRenderer.invoke('library:openFolder'),
  forgetDoc: (id) => ipcRenderer.invoke('library:forget', id),
  locateDoc: (id) => ipcRenderer.invoke('library:locate', id),
  createProject: (name) => ipcRenderer.invoke('project:create', name),
  renameProject: (name) => ipcRenderer.invoke('project:rename', name),
  deleteProject: () => ipcRenderer.invoke('project:delete'),
  chooseStorage: () => ipcRenderer.invoke('storage:choose'),
  presentationStart: () => ipcRenderer.invoke('presentation:start'),
  presentationStop: () => ipcRenderer.invoke('presentation:stop'),
  createDoc: (title) => ipcRenderer.invoke('doc:create', title),
  readDoc: (fileName) => ipcRenderer.invoke('doc:read', fileName),
  saveDoc: (fileName, doc) => ipcRenderer.invoke('doc:save', fileName, doc),
  saveImage: (id, head, data) => ipcRenderer.invoke('doc:image', id, head, data),
  deleteDoc: (fileName) => ipcRenderer.invoke('doc:delete', fileName),
  exportDoc: (doc) => ipcRenderer.invoke('doc:export', doc),
  exportWord: (title, data) => ipcRenderer.invoke('doc:exportWord', title, data),
  exportPdf: (title, job) => ipcRenderer.invoke('doc:exportPdf', title, job),
  exportBook: (title, job) => ipcRenderer.invoke('doc:exportBook', title, job),
  exportEpub: (title, files) => ipcRenderer.invoke('doc:exportEpub', title, files),
  onBookStep: (cb) => ipcRenderer.on('livre:etape', (_e, text) => cb(text)),
  showFile: (filePath) => ipcRenderer.invoke('doc:showFile', filePath),
  listVersions: (docId) => ipcRenderer.invoke('versions:list', docId),
  readVersion: (docId, file) => ipcRenderer.invoke('versions:read', docId, file),
  saveVersion: (doc, kind, label) => ipcRenderer.invoke('versions:save', doc, kind, label),
  deleteVersion: (docId, file) => ipcRenderer.invoke('versions:delete', docId, file),
  importDocs: (kind) => ipcRenderer.invoke('doc:import', kind),
  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  userName: () => ipcRenderer.invoke('app:userName'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  appEdition: () => ipcRenderer.invoke('app:edition'),
  pendingFiles: () => ipcRenderer.invoke('app:pendingFiles'),
  // Chemin d'un fichier glissé sur la fenêtre (vide pour un fichier qui ne vient pas du disque).
  pathOf: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  openDropped: (paths) => ipcRenderer.invoke('app:openDropped', paths),
  onOpenFiles: (callback) => ipcRenderer.on('open-files', (_e, files) => callback(files)),
  assistSuggest: (request) => ipcRenderer.invoke('assist:suggest', request),
  assistCancel: () => ipcRenderer.invoke('assist:cancel'),
  assistGetSettings: () => ipcRenderer.invoke('assist:getSettings'),
  assistWarmUp: () => ipcRenderer.invoke('assist:warmUp'),
  assistChooseFolder: () => ipcRenderer.invoke('assist:chooseFolder'),
  assistSetModel: (id) => ipcRenderer.invoke('assist:setModel', id),
  assistDownloadModel: () => ipcRenderer.invoke('assist:downloadModel'),
  assistCancelDownload: () => ipcRenderer.invoke('assist:cancelDownload'),
  assistDeleteModel: () => ipcRenderer.invoke('assist:deleteModel'),
  assistSummarize: (request) => ipcRenderer.invoke('assist:summarize', request),
  assistSummaryCancel: () => ipcRenderer.invoke('assist:summaryCancel'),
  onSummaryProgress: (callback) => ipcRenderer.on('assist:summaryProgress', (_e, p) => callback(p)),
  assistCoherence: (request) => ipcRenderer.invoke('assist:coherence', request),
  assistCoherenceCancel: () => ipcRenderer.invoke('assist:coherenceCancel'),
  onCoherenceProgress: (callback) => ipcRenderer.on('assist:coherenceProgress', (_e, p) => callback(p)),
  loadSummaries: () => ipcRenderer.invoke('summary:load'),
  saveSummaries: (all) => ipcRenderer.invoke('summary:save', all),
  onAssistDownloadProgress: (callback) => ipcRenderer.on('assist:downloadProgress', (_e, p) => callback(p)),
  officeFonts: () => ipcRenderer.invoke('fonts:officeList'),
  loadOfficeFont: (family) => ipcRenderer.invoke('fonts:officeLoad', family),
  spellCheck: (words, lang) => ipcRenderer.invoke('spell:check', words, lang),
  spellSuggest: (word, lang) => ipcRenderer.invoke('spell:suggest', word, lang),
  detectLanguages: (texts, langs) => ipcRenderer.invoke('lang:detect', texts, langs),
  spellAdd: (word) => ipcRenderer.invoke('spell:add', word),
  synonyms: (word, context, lang) => ipcRenderer.invoke('thesaurus:synonyms', word, context, lang),
  openDictionary: () => ipcRenderer.invoke('spell:openDictionary'),
  onSpellChanged: (callback) => ipcRenderer.on('spell:changed', () => callback()),
  grammarCheck: (text, lang) => ipcRenderer.invoke('grammar:check', text, lang),
  onMenu: (callback) => ipcRenderer.on('menu', (_e, action) => callback(action)),
  onLanguageToolProgress: (callback) => ipcRenderer.on('lt:progress', (_e, p) => callback(p)),
  reportCapture: () => ipcRenderer.invoke('report:capture'),
  reportSave: (report, png) => ipcRenderer.invoke('report:save', report, png),
  reportFolder: () => ipcRenderer.invoke('report:openFolder'),
  setFullScreen: (on) => ipcRenderer.send('window:fullscreen', !!on),
  rebuildMenu: (shortcuts) => ipcRenderer.send('menu:rebuild', shortcuts),
  suspendMenuShortcuts: (on) => ipcRenderer.send('menu:suspend', !!on),
  exportTheme: (name, theme) => ipcRenderer.invoke('theme:export', name, theme),
  importTheme: () => ipcRenderer.invoke('theme:import'),
  exportModel: (name, model) => ipcRenderer.invoke('modele:export', name, model),
  importModel: () => ipcRenderer.invoke('modele:import'),
  loadSources: () => ipcRenderer.invoke('sources:load'),
  saveSources: (list) => ipcRenderer.invoke('sources:save', list),
  importReferences: () => ipcRenderer.invoke('sources:importFile'),
  zoteroCollections: () => ipcRenderer.invoke('sources:zoteroCollections'),
  zoteroItems: (collection) => ipcRenderer.invoke('sources:zoteroItems', collection),
  lookupSource: (text) => ipcRenderer.invoke('sources:lookup', text),
  bioPortrait: (id, file) => ipcRenderer.invoke('bio:portrait', id, file),
  importPdf: () => ipcRenderer.invoke('pdf:import'),
  readPdf: (file) => ipcRenderer.invoke('pdf:read', file),
  pdfjsData: (rel) => ipcRenderer.invoke('pdfjs:data', rel),
  updateCheck: (opts) => ipcRenderer.invoke('update:check', opts),
  updateApply: () => ipcRenderer.invoke('update:apply'),
  updateSettings: () => ipcRenderer.invoke('update:settings'),
  updateChooseFolder: () => ipcRenderer.invoke('update:chooseFolder'),
  updateSetToken: (token) => ipcRenderer.invoke('update:setToken', token),
  onUpdateProgress: (callback) => ipcRenderer.on('update:progress', (_e, step) => callback(step)),
  updateRestart: () => ipcRenderer.send('update:restart'),
  readyToClose: () => ipcRenderer.send('ready-to-close'),
  closeCancelled: () => ipcRenderer.send('close-cancelled'),
  resumed: () => ipcRenderer.invoke('window:resumed'),
  journal: (text) => ipcRenderer.send('journal', String(text).slice(0, 4000))
});
